"""Dataset loader for the user's 2D medical text-guided segmentation format.

Expected layout:
    data/<DatasetName>/<split>/
        images/
        masks/
        train.json | val.json | test.json

Each JSON item should contain at least:
    image, mask, target, modality, body_part

Notes:
    - This loader does not require target_phrase to exist in JSON.
    - If target_phrase exists, it will be used.
    - If target_phrase does not exist, it will be generated by
      steer_medsam.prompt_builder.get_target_phrase().
"""

