IMG_EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff"}


def _load_json_records(json_path: Path) -> List[Dict[str, Any]]:
    with open(json_path, "r", encoding="utf-8") as f:
        obj = json.load(f)

    if isinstance(obj, list):
        return obj

    if isinstance(obj, dict):
        for key in ["data", "samples", "annotations", "items"]:
            if key in obj and isinstance(obj[key], list):
                return obj[key]

    raise ValueError(
        f"Unsupported JSON format in {json_path}. "
        f"Expected list or dict with data/samples/items."
    )


def _resolve_path(split_dir: Path, rel_or_abs: str) -> Path:
    p = Path(rel_or_abs)
    if p.is_absolute():
        return p
    return split_dir / p


def _read_rgb(path: Path) -> np.ndarray:
    img = Image.open(path).convert("RGB")
    return np.asarray(img)


def _read_mask(path: Path) -> np.ndarray:
    mask = Image.open(path).convert("L")
    arr = np.asarray(mask)
    return (arr > 0).astype(np.uint8)


def _resize_image_np(img: np.ndarray, image_size: int) -> np.ndarray:
    pil = Image.fromarray(img)
    pil = pil.resize((image_size, image_size), resample=Image.BILINEAR)
    return np.asarray(pil)


def _resize_mask_np(mask: np.ndarray, image_size: int) -> np.ndarray:
    pil = Image.fromarray((mask > 0).astype(np.uint8) * 255)
    pil = pil.resize((image_size, image_size), resample=Image.NEAREST)
    arr = np.asarray(pil)
    return (arr > 0).astype(np.uint8)


class TextMedSAMDataset(Dataset):
    def __init__(
        self,
        data_root: str | os.PathLike,
        datasets: Sequence[str] | str,
        split: str = "train",
        image_size: int = 1024,
        is_train: bool = True,
        prompt_p_context: float = 0.8,
        eval_prompt_type: str = "context",
        wrong_text: bool = False,
        wrong_target: Optional[str] = None,
        train_box_mode: str = "mixed",
        eval_box_mode: str = "tight",
        bbox_shift: int = 20,
        enlarge_ratio: float = 1.5,
        skip_empty_mask: bool = False,
        seed: int = 2026,
    ) -> None:
        super().__init__()

        self.data_root = Path(data_root)

        if isinstance(datasets, str):
            datasets = [x.strip() for x in datasets.split(",") if x.strip()]
        self.datasets = list(datasets)

        self.split = split
        self.image_size = int(image_size)
        self.is_train = bool(is_train)
        self.prompt_p_context = float(prompt_p_context)
        self.eval_prompt_type = eval_prompt_type
        self.wrong_text = bool(wrong_text)
        self.wrong_target = wrong_target
        self.train_box_mode = train_box_mode
        self.eval_box_mode = eval_box_mode
        self.bbox_shift = int(bbox_shift)
        self.enlarge_ratio = float(enlarge_ratio)
        self.skip_empty_mask = bool(skip_empty_mask)
        self.rng = random.Random(seed)

        self.samples: List[Dict[str, Any]] = []
        self._load_all_samples()

        if not self.samples:
            raise RuntimeError(
                f"No samples found in {self.data_root} "
                f"for datasets={self.datasets}, split={split}"
            )

    def _load_all_samples(self) -> None:
        for ds_name in self.datasets:
            split_dir = self.data_root / ds_name / self.split
            json_path = split_dir / f"{self.split}.json"

            if not json_path.exists():
                candidates = sorted(split_dir.glob("*.json"))
                if not candidates:
                    raise FileNotFoundError(
                        f"No JSON file found for {ds_name}/{self.split}: {json_path}"
                    )
                json_path = candidates[0]

            records = _load_json_records(json_path)

            for idx, rec in enumerate(records):
                if "image" not in rec or "mask" not in rec:
                    continue

                item = dict(rec)

                # dataset: user-facing dataset name.
                # _dataset_name: canonical folder-level dataset name, useful for target_phrase mapping.
                item["dataset"] = item.get("dataset", ds_name)
                item["_dataset_name"] = ds_name

                item["split_dir"] = str(split_dir)
                item["json_path"] = str(json_path)
                item["record_index"] = idx
                item["image_path"] = str(_resolve_path(split_dir, item["image"]))
                item["mask_path"] = str(_resolve_path(split_dir, item["mask"]))

                self.samples.append(item)

    def __len__(self) -> int:
        return len(self.samples)

    def _build_text(self, sample):
        if self.wrong_text:
            raise ValueError("wrong_text template evaluation is outside the question-only protocol")
        return question_text(sample)

    def __getitem__(self, index: int) -> Dict[str, Any]:
        allow_resample = self.is_train and self.skip_empty_mask
        # Resample on empty/corrupt masks if requested.
        for _ in range(10):
            sample = self.samples[index]

            try:
                image_path = Path(sample["image_path"])
                mask_path = Path(sample["mask_path"])

                image = _read_rgb(image_path)
                mask = _read_mask(mask_path)

                if self.skip_empty_mask and mask.sum() == 0:
                    raise ValueError(f"Empty mask: {mask_path}")

                break

            except Exception:
                if not allow_resample:
                    raise
                index = self.rng.randrange(len(self.samples))
        else:
            raise RuntimeError("Failed to fetch a valid non-empty mask after 10 attempts.")

        orig_h, orig_w = image.shape[:2]

        image_rs = _resize_image_np(image, self.image_size)
        mask_rs = _resize_mask_np(mask, self.image_size)

        box = stage1_box(mask_rs, training=self.is_train,
                         mode=self.train_box_mode if self.is_train else self.eval_box_mode,
                         shift=self.bbox_shift, enlarge_ratio=self.enlarge_ratio, rng=self.rng)

        image_t = torch.from_numpy(image_rs.astype(np.float32) / 255.0)
        image_t = image_t.permute(2, 0, 1).contiguous()

        mask_t = torch.from_numpy(mask_rs.astype(np.float32))[None, ...].contiguous()
        box_t = torch.tensor(box, dtype=torch.float32)

        dataset_name = sample.get("_dataset_name", sample.get("dataset", "unknown"))
        target_phrase = get_target_phrase(sample, dataset_name=dataset_name)
        text = self._build_text(sample)

        return {
            "image": image_t,
            "mask": mask_t,
            "box": box_t,
            "text": text,
            "dataset": sample.get("dataset", dataset_name),
            "dataset_name": dataset_name,
            "target": sample.get("target", "target"),
            "target_phrase": target_phrase,
            "modality": sample.get("modality", ""),
            "body_part": sample.get("body_part", ""),
            "image_path": str(image_path),
            "mask_path": str(mask_path),
            "original_size": torch.tensor([orig_h, orig_w], dtype=torch.long),
            "record_index": int(sample.get("record_index", index)),
        }


def text_medsam_collate(batch: List[Dict[str, Any]]) -> Dict[str, Any]:
    out: Dict[str, Any] = {}

    tensor_keys = ["image", "mask", "box", "original_size"]
    for k in tensor_keys:
        out[k] = torch.stack([b[k] for b in batch], dim=0)

    list_keys = [
        "text",
        "dataset",
        "dataset_name",
        "target",
        "target_phrase",
        "modality",
        "body_part",
        "image_path",
        "mask_path",
    ]
    for k in list_keys:
        out[k] = [b[k] for b in batch]

    out["record_index"] = torch.tensor(
        [b["record_index"] for b in batch],
        dtype=torch.long,
    )

    return out